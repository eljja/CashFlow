def parse_fin_rows(rows, unit="Billion USD", unit_mult=1e9):
    fin_list = []
    for row in rows:
        (yr, rev, op_inc, net_inc, ocf, capex, fcf, icf, fin_cf, div_p, buyb, net_ch, cash_eq, st_inv, debt) = row
        tot_cash = cash_eq + st_inv
        net_cash = tot_cash - debt
        fcf_m = round((fcf / rev) * 100, 2) if rev != 0 else 0
        fcf_c = round((fcf / net_inc) * 100, 2) if net_inc != 0 else 0
        ocf_capex = round(ocf / capex, 2) if capex != 0 else 0
        tot_sh_ret = round(div_p + buyb, 2)
        fin_list.append({
            "year": yr, "revenue": rev, "operatingIncome": op_inc, "netIncome": net_inc,
            "operatingCashFlow": ocf, "capitalExpenditure": capex, "freeCashFlow": fcf,
            "investingCashFlow": icf, "financingCashFlow": fin_cf,
            "dividendsPaid": div_p, "shareRepurchase": buyb, "totalShareholderReturn": tot_sh_ret,
            "netChangeInCash": net_ch, "cashAndEquivalents": cash_eq, "shortTermInvestments": st_inv,
            "totalCash": round(tot_cash, 2), "totalDebt": debt, "netCash": round(net_cash, 2),
            "fcfMargin": fcf_m, "fcfConversion": fcf_c, "ocfToCapex": ocf_capex
        })
    return fin_list

